"""Regenerate the indexed transform-feedback probe's embedded SPIR-V.

Run from any directory:
  python3 src/asahi/vulkan/tests/gen_g17p_transform_feedback_indexed.py
Requires glslangValidator on PATH. The generated header is committed so normal
Mesa builds do not require this tool.
"""

import pathlib
import struct
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent
SHADERS = (
    ("g17p_vulkan_transform_feedback_indexed.vert", "g17p_xfb_indexed_vert_spv"),
    ("g17p_vulkan_transform_feedback_indexed.geom", "g17p_xfb_passthrough_geom_spv"),
    ("g17p_vulkan_transform_feedback_indexed_auto.vert", "g17p_xfb_indexed_auto_vert_spv"),
)

output = [
    "/* Generated by gen_g17p_transform_feedback_indexed.py.",
    " * Sources: companion indexed .vert/.geom files. SPDX-License-Identifier: MIT */",
    "#pragma once",
    "",
]
with tempfile.TemporaryDirectory(prefix="g17p-xfb-spirv-") as directory:
    for source, symbol in SHADERS:
        binary = pathlib.Path(directory) / (source + ".spv")
        subprocess.run(["glslangValidator", "-V", str(ROOT / source), "-o", str(binary)], check=True)
        data = binary.read_bytes()
        words = struct.unpack("<" + "I" * (len(data) // 4), data)
        output.append(f"static const uint32_t {symbol}[] = {{")
        for i in range(0, len(words), 4):
            output.append("   " + ", ".join(f"0x{v:08x}" for v in words[i:i + 4]) + ",")
        output.extend(["};", ""])
(ROOT / "g17p_vulkan_transform_feedback_indexed.h").write_text("\n".join(output))
